using System.Text;

namespace CobolCS.Frontend.Parsing;

/// <summary>参照実装と同じUnicode 15.0.0 の複数文字大文字化を保持します。</summary>
internal static class SourceCasing
{
    /// <summary>識別子をUnicodeスカラー単位で大文字化し、ßなどの展開も保持します。</summary>
    /// <param name="text">比較する文字列。</param>
    /// <returns>大文字化した比較用文字列。原文は変更しません。</returns>
    internal static string Upper(string text)
    {
        var result = new StringBuilder();
        foreach (var rune in text.EnumerateRunes())
        {
            result.Append(rune.Value switch
            {
                0xDF => "SS",
                0x149 => "ʼN",
                0x1F0 => "J̌",
                0x390 => "Ϊ́",
                0x3B0 => "Ϋ́",
                0x587 => "ԵՒ",
