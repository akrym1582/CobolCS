                0x1F52 => "Υ̓̀",
                0x1F54 => "Υ̓́",
                0x1F56 => "Υ̓͂",
                0x1F80 => "ἈΙ",
                0x1F81 => "ἉΙ",
                0x1F82 => "ἊΙ",
                0x1F83 => "ἋΙ",
                0x1F84 => "ἌΙ",
