using System.Security.Cryptography;
using System.Text;
using System.Text.Json;
using System.Text.Json.Nodes;
using CobolCS.Runtime;

namespace CobolCS.Cli;

public static class Generator
{
    public const string Version = "0.1.0";
    public const string CobolTsCommit = "3e42de61fa8e0e7747e37cb17a48732ac962e38d";
    public static readonly JsonSerializerOptions JsonOptions = new() { WriteIndented = true };
    public static string Json(JsonNode node) => node.ToJsonString(JsonOptions) + "\n";
    public static string Hash(byte[] bytes) => Convert.ToHexStringLower(SHA256.HashData(bytes));
    public static void SafePath(string path)
    {
        var current = Path.GetFullPath(path);
        while (!string.IsNullOrEmpty(current))
        {
            if ((File.Exists(current) || Directory.Exists(current)) && File.GetAttributes(current).HasFlag(FileAttributes.ReparsePoint)) throw new IOException("Symlink output path refused: " + current);
            current = Path.GetDirectoryName(current) ?? "";
        }
    }
    public static JsonNode ReadManifest(string output)
    {
        SafePath(output);
        return J.Parse(File.ReadAllText(Path.Combine(output, "manifest.json")));
    }
    public static void Verify(string output, JsonNode manifest)
    {
        if (manifest["artifacts"] is not JsonObject artifacts) throw new IOException("Invalid CobolCS manifest");
        foreach (var (name, value) in artifacts)
        {
            if (Path.IsPathRooted(name) || name.Contains('\\') || name.Split('/').Any(p => p is ".." or "." or "")) throw new IOException("Unsafe manifest artifact path");
            var file = Path.Combine(output, name); SafePath(file);
            if (!File.Exists(file) || Hash(File.ReadAllBytes(file)) != value!.GetValue<string>()) throw new IOException("Generated file edited or removed: " + name);
        }
    }
    public static void SaveManifest(string output, JsonNode manifest)
    {
        var path = Path.Combine(output, "manifest.json"); SafePath(path);
        var temporary = path + ".tmp"; SafePath(temporary);
        File.WriteAllText(temporary, Json(manifest)); File.Move(temporary, path, overwrite: true);
    }
    public static JsonNode Generate(JsonNode ir, string output, string mode)
    {
        output = Path.GetFullPath(output); SafePath(output);
        var diagnostics = Validation.Check(ir); var errors = diagnostics.Any(d => d!.S("severity") == "error");
        var generated = mode != "analyze" && (mode == "scaffold" || !errors);
        var files = new SortedDictionary<string, string>(StringComparer.Ordinal)
        {
            ["reports/ir.json"] = Json(ir), ["reports/diagnostics.json"] = Json(diagnostics),
            ["reports/diagnostics.md"] = string.Join('\n', diagnostics.Select(d => $"- {d!.S("code")}: {d!.S("message")} ({d!["source"]?.S("file")}:{d!["source"]?["start"]?.I("line")})")) + "\n",
            ["reports/dependencies.json"] = Json(new JsonArray(ir.A("programs").Select(p => (JsonNode?)new JsonObject { ["program"] = p.S("id"), ["dependencies"] = p["dependencies"]!.DeepClone() }).ToArray())),
            ["reports/ai-brief.md"] = "# CobolCS review\n\nReview reports/diagnostics.json and reports/ir.json. Change frontend/compiler/runtime, regenerate and run regression tests. Build and fixture success do not establish business equivalence.\n"
        };
        if (generated)
        {
            files["CobolCS.Generated.csproj"] = "<Project Sdk=\"Microsoft.NET.Sdk\"><PropertyGroup><TargetFramework>net10.0</TargetFramework><OutputType>Exe</OutputType><ImplicitUsings>enable</ImplicitUsings><Nullable>enable</Nullable><TreatWarningsAsErrors>true</TreatWarningsAsErrors></PropertyGroup><ItemGroup><EmbeddedResource Include=\"reports/ir.json\" LogicalName=\"CobolCS.IR\" /></ItemGroup></Project>\n";
            foreach (var path in Directory.GetFiles(Path.Combine(AppContext.BaseDirectory, "runtime"), "*.cs")) files["Runtime/" + Path.GetFileName(path)] = File.ReadAllText(path);
            var index = 0;
            foreach (var program in ir.A("programs"))
            {
                var source = new StringBuilder("// Generated by CobolCS. Source locations are preserved in each instruction.\nusing System.Text.Json.Nodes;\nusing CobolCS.Runtime;\n\n");
                source.AppendLine($"internal static class Program_{index:D4}\n{{\n    public static JsonObject Run(JsonNode program, JsonNode config, JsonNode? fixture)\n    {{");
                if (errors) source.AppendLine("        throw new NotSupportedException(\"Scaffold requires review. See reports/diagnostics.json.\");");
                else
                {
                    source.AppendLine("        Instruction[] flow =\n        [");
                    foreach (var instruction in FlowBuilder.Build(program))
                    {
                        var node = instruction.Node;
                        var raw = node?["source"]?.S("raw").Replace('\r', ' ').Replace('\n', ' ');
                        if (!string.IsNullOrEmpty(raw)) source.AppendLine("            // " + raw);
                        source.AppendLine($"            new({JsonSerializer.Serialize(instruction.Op)}, {(node == null ? "null" : "J.Parse(" + JsonSerializer.Serialize(node.ToJsonString()) + ")")}, {instruction.Next}, {instruction.Alternate}),");
                    }
                    source.AppendLine("        ];\n        return new Machine(program, config, fixture).Run(flow, program);");
                }
                source.AppendLine("    }\n}"); files[$"Programs/Program_{index++:D4}.cs"] = source.ToString();
            }
            var runner = new StringBuilder("using System.Text.Json;\nusing System.Text.Json.Nodes;\nusing CobolCS.Runtime;\n\ntry\n{\n    if (args.Length is < 1 or > 2) throw new ArgumentException(\"Usage: <PROGRAM-ID> [fixture.json]\");\n    using var stream = typeof(Program).Assembly.GetManifestResourceStream(\"CobolCS.IR\")!;\n    var ir = JsonNode.Parse(stream)!;\n    var fixture = args.Length == 2 ? J.Parse(File.ReadAllText(args[1])) : null;\n    var programs = ir.A(\"programs\").ToArray();\n    JsonObject result = args[0] switch\n    {\n");
            index = 0;
            foreach (var p in ir.A("programs")) { runner.AppendLine($"        {JsonSerializer.Serialize(p.S("id"))} => Program_{index:D4}.Run(programs[{index}], ir[\"config\"]!, fixture),"); index++; }
            runner.AppendLine("        _ => throw new ArgumentException(\"Unknown PROGRAM-ID \" + args[0])\n    };\n    Console.WriteLine(result.ToJsonString(new JsonSerializerOptions { WriteIndented = true }));\n    return 0;\n}\ncatch (Exception e)\n{\n    Console.Error.WriteLine(e.Message);\n    return 2;\n}"); files["Program.cs"] = runner.ToString();
            files["LICENSE"] = File.ReadAllText(Path.Combine(AppContext.BaseDirectory, "licenses/CobolCS.txt"));
        }
        var artifactHashes = new JsonObject(); foreach (var (path, content) in files) artifactHashes[path] = Hash(Encoding.UTF8.GetBytes(content));
        var inputs = new JsonObject(); foreach (var input in ir.A("sources")) inputs[input.S("path")] = input.S("sha256");
        var manifest = new JsonObject
        {
            ["toolVersion"] = Version, ["cobolTsCommit"] = CobolTsCommit, ["pythonBolCommit"] = ir.S("upstreamCommit"), ["configHash"] = ir.S("configHash"),
            ["inputHashes"] = inputs, ["artifacts"] = artifactHashes, ["programs"] = new JsonArray(ir.A("programs").Select(p => (JsonNode?)JsonValue.Create(p.S("id"))).ToArray()),
            ["judgments"] = new JsonObject { ["analyzed"] = !ir.A("diagnostics").Any(d => d.S("code") is "PARSE_ERROR" or "INPUT_DECODE"), ["generated"] = generated, ["built"] = false, ["executedWithFixtures"] = false, ["matchedBaseline"] = false, ["needsReview"] = diagnostics.Count != 0 }
        };
        files["manifest.json"] = Json(manifest);
        if (Directory.Exists(output) && Directory.EnumerateFileSystemEntries(output).Any())
        {
            var previous = ReadManifest(output); Verify(output, previous);
            foreach (var directory in Directory.EnumerateDirectories(output, "*", SearchOption.AllDirectories)) SafePath(directory);
            foreach (var file in Directory.EnumerateFiles(output, "*", SearchOption.AllDirectories))
            {
                SafePath(file);
                var relative = Path.GetRelativePath(output, file).Replace('\\', '/');
                if (relative.StartsWith("bin/") || relative.StartsWith("obj/")) continue;
                if (relative != "manifest.json" && previous["artifacts"]?[relative] == null) throw new IOException("Unmanaged file prevents regeneration: " + relative);
            }
        }
        var stage = output + ".stage-" + Guid.NewGuid().ToString("N"); var backup = output + ".backup-" + Guid.NewGuid().ToString("N");
        try
        {
            foreach (var (path, content) in files) { var target = Path.Combine(stage, path); Directory.CreateDirectory(Path.GetDirectoryName(target)!); File.WriteAllText(target, content, new UTF8Encoding(false)); }
            if (Directory.Exists(output)) Directory.Move(output, backup);
            try { Directory.Move(stage, output); }
            catch { if (Directory.Exists(backup)) Directory.Move(backup, output); throw; }
            if (Directory.Exists(backup)) Directory.Delete(backup, recursive: true);
        }
        finally { if (Directory.Exists(stage)) Directory.Delete(stage, recursive: true); }
        return manifest;
    }
}
