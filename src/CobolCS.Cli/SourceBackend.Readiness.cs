using System.Text;
using System.Text.Json.Nodes;
using CobolCS.Runtime;

namespace CobolCS.Cli;

/// <summary>実行に必要な入力と応答の編集先を静的に案内します。</summary>
internal sealed partial class SourceBackend
{
    private readonly List<string> responseExamples = [];

    /// <summary>ユーザー領域でも通常の警告検査を適用します。</summary>
    /// <param name="source">初回テンプレート。</param>
    /// <returns>生成済みマーカーを含まないコード。</returns>
    private static string UserSource(string source) => source.ReplaceLineEndings("\n").Replace("// <auto-generated/>\n", string.Empty, StringComparison.Ordinal).Replace("using System.Text.Json.Nodes;\n", string.Empty, StringComparison.Ordinal).Replace("{\n\n", "{\n", StringComparison.Ordinal).Replace("\n\n}", "\n}", StringComparison.Ordinal);

    /// <summary>文別の fake 登録例を作ります。登録順は推測しません。</summary>
    /// <param name="statement">文。</param>
    /// <param name="method">契約メソッド。</param>
    /// <param name="inputs">依頼項目。</param>
    /// <param name="outputs">応答項目。</param>
    private void ResponseExample(JsonNode statement, string method, List<(string Type, string Name, string Expression)> inputs, List<(string Type, string Name, JsonNode Reference)> outputs)
    {
        var request = name + method + "Request";
        var response = name + method + "Response";
        var code = new StringBuilder($"/// <summary>文別の検査と応答を設定します。</summary>\n/// <param name=\"fake\">このケースの応答列。</param>\npublic static void Register_{statement.S("id")}({name}ScriptedDependencies fake)\n{{\n// {Location(statement)}\n// Inspect target, ordered arguments, passing modes and inputs:\n");
        var dependency = program.A("dependencies").FirstOrDefault(d => d.S("id") == statement.S("dependencyId"));
        code.AppendLine("// Passing modes in argument order: " + string.Join(", ", dependency?.A("modes").Select(m => m.GetValue<string>()) ?? []));
        foreach (var item in inputs)
        {
            code.AppendLine($"// request.{item.Name}: {item.Type}");
        }

        code.AppendLine($"bool Match({request} request) => Preparation.Required<bool>({Quote(Location(statement) + " matcher: inspect request values")});\nvar response = new {response}(StatusCode: Preparation.Required<string>({Quote(Location(statement) + " status")}), Outcome: Preparation.Required<DependencyOutcome>({Quote(Location(statement) + " outcome")}))\n{{");
        foreach (var item in outputs)
        {
            code.AppendLine($"\n// {item.Name}: {item.Type}; PIC {symbols[item.Reference.S("symbolId")]["pic"]?.S("raw") ?? "complete fixed group"}. default means no update.");
            code.AppendLine($"{item.Name} = {(symbols[item.Reference.S("symbolId")]["pic"] == null ? ArgumentExample(symbols[item.Reference.S("symbolId")], Location(statement) + " response " + item.Name) : $"Preparation.Required<{item.Type}>({Quote(Location(statement) + " response " + item.Name)})")},");
        }

        code.AppendLine($"}};\n\n// FILE: 00/Normal requires record; 10/End omits record and sets FileStatus.\n// SQL: 0/Normal, 100/End, negative/Exception; set SQLCODE/SQLSTATE explicitly.\n// SQL NULL: negative indicator with omitted Host; no-data/error omit data outputs.\n// CALL: Reference outputs are optional; supplied groups must be complete snapshots.\nfake.Expect{method}(Match, response);\n}}");
        responseExamples.Add(code.ToString() + "\n");
    }

    /// <summary>業務値を推測せず、各必須項目の記入箇所を展開します。</summary>
    /// <param name="symbol">引数宣言。</param>
    /// <param name="label">失敗時の準備項目名。</param>
    /// <returns>コンパイル可能な未設定値構築式。</returns>
    private string ArgumentExample(JsonNode symbol, string label)
    {
        if (symbol["pic"] != null)
        {
            return $"Preparation.Required<{ArgumentType(symbol)}>({Quote(label)})";
        }

        var parameters = LayoutLeaves(symbol).Select(s => $"{Member(s)}: Preparation.Required<{(Dimensions(s).Length == 0 ? TypeName(s) : $"IReadOnlyList<{TypeName(s)}>")}>({Quote(label + " / " + s.S("qualifiedName"))})");
        return $"new {ArgumentType(symbol)}({string.Join(", ", parameters)})";
    }

    /// <summary>入力例、テストと準備レポートを生成します。</summary>
    private void Readiness()
    {
        var scenarioPath = $"UserCode/Scenarios/{name}Scenarios.cs";
        var responsePath = $"UserCode/Scenarios/{name}ResponseExamples.cs";
        files[responsePath] = UserSource(Header() + $"/// <summary>必要な文だけをケース順に登録する応答例。</summary>\npublic static class {name}ResponseExamples\n{{\n" + string.Concat(responseExamples) + "}\n");
        var accepts = Validation.Walk(program["paragraphs"]).Where(s => s.S("kind") == "acceptInput").DistinctBy(s => s.S("id")).OrderBy(s => s.S("id"), StringComparer.Ordinal).ToArray();
        var code = new StringBuilder(Header() + $"/// <summary>このプログラムのケース別入力と応答。</summary>\npublic static class {name}Scenarios\n{{\n/// <summary>入力と応答を記入するサンプル。</summary>\n/// <param name=\"options\">実行制限。</param>\n/// <returns>観測結果。</returns>\npublic static {name}Result Sample(ExecutionOptions options)\n{{\nvar input = new {name}Input\n{{\n// Static ACCEPT candidates below are not a predicted consumption order.\n// Edit the queue for this case, including branches and repetitions.\nAcceptInputs = new string[]\n{{\n");
        foreach (var accept in accepts)
        {
            code.AppendLine($"Preparation.Required<string>({Quote(Location(accept) + " ACCEPT " + accept["target"]?.S("symbolId"))}),");
        }

        code.AppendLine("},\nArguments = new()\n{");
        foreach (var argument in program.A("using"))
        {
            if (symbols.TryGetValue(argument.S("symbolId"), out var symbol) && FixedLayout(symbol))
            {
                code.AppendLine($"{Member(symbol)} = new Optional<{ArgumentType(symbol)}>({ArgumentExample(symbol, "LINKAGE " + symbol.S("qualifiedName"))}),");
            }
        }

        code.AppendLine($"}},\n\n// Optional test setup: InitialState = new() {{ /* WORKING-STORAGE fields only */ }},\n}};\nvar fake = new {name}ScriptedDependencies();\n\n// Register only responses consumed by this case, in actual execution order.\n// See {name}ResponseExamples.Register_* methods.\nreturn new {name}Executor().Run(input, fake, options);\n}}\n}}");
        files[scenarioPath] = UserSource(code.ToString());
        var test = new StringBuilder(Header().Replace("namespace CobolCS.Generated;", "using Microsoft.VisualStudio.TestTools.UnitTesting;\n\nnamespace CobolCS.Generated.Tests;") + $"/// <summary>期待値を記入しレビューする回帰試験。</summary>\n[TestClass]\npublic sealed class {name}Tests\n{{\n/// <summary>ケースの観測結果を固定します。</summary>\n[TestMethod]\npublic void {name}_Sample()\n{{\nvar result = {name}Scenarios.Sample(new ExecutionOptions());\nReview.Require({Quote(program.S("id"))}, {Quote(name + "_Sample")}, result.CallStubMode, result.HasNoOpCalls);\nCollectionAssert.AreEqual(Preparation.Required<string[]>(\"expected Display\"), result.Display.ToArray());\nAssert.AreEqual(Preparation.Required<TerminationKind>(\"expected Termination\"), result.Termination);\nAssert.HasCount(Preparation.Required<int>(\"expected dependency count\"), result.DependencyTrace);\n\n// Inspect typed Request values on the corresponding RequestTrace; fake matchers check each request.\n");
        var assertionCandidates = AssertionCandidates();
        AppendCandidateAssertions(test, assertionCandidates);
        test.AppendLine("\n// To test fake responses, call " + name + "ScriptedScenarios.Sample and include the scenario and response configuration in Tests/review.json files.");

        foreach (var argument in program.A("using"))
        {
            if (symbols.TryGetValue(argument.S("symbolId"), out var symbol) && FixedLayout(symbol))
            {
                test.AppendLine("Assert.IsNotNull(result.Arguments);");
                var expected = $"Preparation.Required<{ArgumentType(symbol)}>({Quote("expected Arguments " + symbol.S("qualifiedName"))})";
                var actual = $"result.Arguments.{Member(symbol)}";
                test.AppendLine(symbol["pic"] == null ? $"Assert.IsTrue({actual}.ContentEquals({expected}));" : Dimensions(symbol).Length == 0 ? $"Assert.AreEqual({expected}, {actual});" : $"CollectionAssert.AreEqual({expected}.ToArray(), {actual}.ToArray());");
            }
        }

        files[$"Tests/Cases/{name}Tests.cs"] = UserSource(test.AppendLine("}\n}").ToString());
        var report = J.Parse(files["reports/execution-readiness.json"]);
        var items = report["items"]!.AsArray();
        void Add(string category, JsonNode node, string edit, string contract, string reason, JsonNode? dependency = null)
        {
            var targets = Validation.Walk(node).Where(n => symbols.ContainsKey(n.S("symbolId"))).Select(n => symbols[n.S("symbolId")]).Concat(symbols.TryGetValue(node.S("id"), out var declared) ? [declared] : []).DistinctBy(s => s.S("id"));
            items.Add(new JsonObject
            {
                ["programId"] = program.S("id"),
                ["statementId"] = node.S("id"),
                ["source"] = node["source"] == null ? null : new JsonObject { ["file"] = node["source"]!["file"]?.DeepClone(), ["start"] = node["source"]!["start"]?.DeepClone(), ["end"] = node["source"]!["end"]?.DeepClone() },
                ["classification"] = category,
                ["reason"] = reason,
                ["editFile"] = edit,
                ["contractType"] = contract,
                ["fields"] = new JsonArray(targets.Select(s => (JsonNode?)new JsonObject { ["symbolId"] = s.S("id"), ["name"] = s.S("qualifiedName"), ["pic"] = s["pic"]?.DeepClone(), ["dimensions"] = new JsonArray(Dimensions(s).Select(d => (JsonNode?)JsonValue.Create(d)).ToArray()), ["groupMembers"] = s["pic"] == null ? new JsonArray(LayoutLeaves(s).Select(l => (JsonNode?)new JsonObject { ["symbolId"] = l.S("id"), ["name"] = l.S("qualifiedName"), ["pic"] = l["pic"]?.DeepClone() }).ToArray()) : null }).ToArray()),
                ["requestType"] = dependency == null || category.StartsWith("unsupported-", StringComparison.Ordinal) ? null : name + "Dependency_" + node.S("id") + "Request",
                ["responseType"] = dependency == null || category.StartsWith("unsupported-", StringComparison.Ordinal) ? null : name + "Dependency_" + node.S("id") + "Response",
                ["exampleMethod"] = dependency == null || category.StartsWith("unsupported-", StringComparison.Ordinal) ? null : "Register_" + node.S("id"),
                ["direction"] = dependency == null ? "input" : "request/response",
                ["target"] = dependency?["call"]?["target"]?.DeepClone(),
                ["passingModes"] = dependency?["modes"]?.DeepClone() ?? node["mode"]?.DeepClone(),
                ["inputs"] = dependency?["inputs"]?.DeepClone(),
                ["outputs"] = dependency?["outputs"]?.DeepClone(),
                ["returning"] = dependency?["call"]?["returning"]?.DeepClone(),
                ["reference"] = "reports/source-map.json; reports/stubs.json; reports/ir.json",
            });
            files["reports/execution-readiness.md"] += $"- `{program.S("id")}` `{node.S("id")}` **{category}**: {reason}. Edit `{edit}`; type `{contract}`.\n";
        }

        foreach (var accept in accepts)
        {
            Add("accept-input", accept, scenarioPath, name + "Input.AcceptInputs", "Supply this case's consumption sequence");
        }

        foreach (var argument in program.A("using"))
        {
            var node = argument.DeepClone();
            node["id"] = "linkage_" + argument.S("symbolId");
            node["source"] = symbols[argument.S("symbolId")]["source"]?.DeepClone();
            Add("linkage-input", node, scenarioPath, name + "Arguments", SupportedUsing() ? "Required explicit argument; InitialState is forbidden" : "Unsupported declaration mode or layout; entry stub retained");
        }

        foreach (var stub in stubs.Where(s => s!.S("programId") == program.S("id")))
        {
            var dependency = stub!["dependency"];
            var category = dependency == null ? "unsupported-internal" : dependency.S("kind") + "-response";
            if (dependency == null && stub["statement"]!.S("kind") == "external")
            {
                dependency = program.A("dependencies").FirstOrDefault(d => d.S("id") == stub["statement"]!.S("dependencyId"));
                category = "unsupported-" + (dependency?.S("kind") ?? "external");
            }

            Add(category, stub["statement"]!, stub.S("capability") == "unsupported" ? stub.S("file") : responsePath, stub.S("signature"), stub.S("reason"), dependency);
        }

        foreach (var symbol in symbols.Values.Where(s => s.I("level") != 88 && (s.B("stub") || (s["pic"] != null && !Known(s)))))
        {
            Add("unknown-declaration", symbol, "reports/diagnostics.json", "UnknownCobolValue", "Resolve layout before supplying this argument or accessing this field");
        }

        report["assertionCandidates"] ??= new JsonArray();
        foreach (var candidate in assertionCandidates)
        {
            report["assertionCandidates"]!.AsArray().Add(candidate!.DeepClone());
            files["reports/execution-readiness.md"] += $"- Static update candidate `{program.S("id")}` `{candidate.S("symbolId")}` `{candidate.S("name")}`: {candidate.S("status")}; comparison `{candidate.S("assertionMember")}` in `{candidate.S("testFile")}`. Templates require independent expected values and review; this does not establish executed-path coverage.\n";
        }

        files["reports/execution-readiness.json"] = Generator.Json(report);
    }
}
